#!/usr/bin/env python3
"""Renders agent logos (Simple Icons SVGs) into firmware/src/icons.h as 8-bit alpha masks.

Usage: tools/gen-agent-icons.py <dir with claude.svg openai.svg googlegemini.svg cursor.svg githubcopilot.svg>
Get the SVGs from https://cdn.jsdelivr.net/npm/simple-icons@<version>/icons/<slug>.svg (CC0).
Needs Google Chrome (headless) to rasterize the paths with antialiasing.
"""
import html, json, os, re, subprocess, sys, tempfile

SIMPLE_ICONS = "15.22.0"
SIZES = {"big": 44, "small": 22}
# slug, C name, tint (brand colour, or white where the brand colour is black on our dark UI)
ICONS = [
    ("claude", "claude", (0xD9, 0x77, 0x57)),
    ("openai", "openai", (0xF0, 0xF0, 0xF0)),
    ("googlegemini", "gemini", (0x8E, 0x75, 0xFF)),
    ("cursor", "cursor", (0xF0, 0xF0, 0xF0)),
    ("githubcopilot", "copilot", (0xF0, 0xF0, 0xF0)),
]
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
OUT = os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "icons.h")

src = sys.argv[1]
paths = {}
for slug, _, _ in ICONS:
    svg = open(os.path.join(src, slug + ".svg")).read()
    paths[slug] = re.search(r' d="([^"]+)"', svg).group(1)

page = """<!doctype html><body><pre id="out"></pre><script>
const paths = %s, sizes = %s, out = {};
for (const [slug, d] of Object.entries(paths)) for (const [k, n] of Object.entries(sizes)) {
  const c = document.createElement('canvas'); c.width = c.height = n;
  const g = c.getContext('2d'); g.scale(n / 24, n / 24); g.fill(new Path2D(d));
  const px = g.getImageData(0, 0, n, n).data, a = [];
  for (let i = 3; i < px.length; i += 4) a.push(px[i]);
  out[slug + ':' + k] = a;
}
document.getElementById('out').textContent = JSON.stringify(out);
</script></body>""" % (json.dumps(paths), json.dumps(SIZES))

with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False) as f:
    f.write(page)
dom = subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--dump-dom", "file://" + f.name],
                     capture_output=True, text=True).stdout
os.unlink(f.name)
masks = json.loads(html.unescape(re.search(r'<pre id="out">(.*?)</pre>', dom, re.S).group(1)))

lines = [
    "#pragma once",
    "// Generated by tools/gen-agent-icons.py from Simple Icons %s (CC0). The logos are" % SIMPLE_ICONS,
    "// trademarks of their owners, shown only to identify which agent is connected.",
    "// 8-bit alpha masks, row-major.",
    "#include <stdint.h>",
    "",
]
for slug, name, _ in ICONS:
    for k, n in SIZES.items():
        a = masks[slug + ":" + k]
        lines.append("static const uint8_t ICON_%s_%s[%d * %d] = {" % (name.upper(), k.upper(), n, n))
        for r in range(n):
            lines.append("  " + ",".join(str(v) for v in a[r * n:(r + 1) * n]) + ",")
        lines.append("};")
lines += [
    "",
    "struct AgentIcon {",
    "  const char* names;  // '|'-separated, matched case-insensitively as substrings of the agent name",
    "  uint8_t r, g, b;",
    "  const uint8_t *big, *small;",
    "};",
    "static constexpr int ICON_BIG = %d, ICON_SMALL = %d;" % (SIZES["big"], SIZES["small"]),
    "static const AgentIcon AGENT_ICONS[] = {",
]
NAMES = {"claude": "claude|anthropic", "openai": "codex|openai|chatgpt|gpt", "gemini": "gemini|google",
         "cursor": "cursor", "copilot": "copilot"}
for slug, name, (r, g, b) in ICONS:
    lines.append('  {"%s", %d, %d, %d, ICON_%s_BIG, ICON_%s_SMALL},' % (NAMES[name], r, g, b, name.upper(), name.upper()))
lines += ["};", ""]
open(OUT, "w").write("\n".join(lines))
print("wrote", os.path.normpath(OUT))
